import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 900, height: 650 }, deviceScaleFactor: 1 });
const logs = [];
page.on('console', (m) => { const t = m.text(); if (!/vite|DevTools|THREE.Clock/.test(t)) logs.push(`[${m.type()}] ${t}`); });
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.addInitScript(() => localStorage.setItem('zefs-dry-night-quest:welcomed', '1'));
// seed: castle earned earlier, then a wet night reset the journey (keepsakes 1-15 remain)
await page.goto('http://127.0.0.1:5173/?debug&speed=1.5', { waitUntil: 'load' });
await page.waitForTimeout(4000);
await page.evaluate(() => {
  const z = window.__zef;
  z.recordRun(15, -1);
  z.record(0, 'wet');
  const d = z.save();
  localStorage.setItem('zefs-dry-night-quest:v1', JSON.stringify({ ...d, seen: { stop: 0, hugDate: d.seen.hugDate ?? Object.keys(d.records).sort().pop(), streak: 0 } }));
});
await page.reload({ waitUntil: 'load' });
await page.waitForTimeout(7000);
console.log(JSON.stringify(await page.evaluate(() => ({ lit: window.__zef.game().litStop, scene: window.__zef.game().scene, castle: window.__zef.save().castleUnlocked, keep: window.__zef.save().keepsakes.length }))));
await page.screenshot({ path: 'scripts/out/extra-01-cottage-balloon.png', timeout: 120000 });
await page.evaluate(() => window.__zef.shelf());
await page.waitForTimeout(6000);
await page.screenshot({ path: 'scripts/out/extra-02-shelf.png', timeout: 120000 });
// ride the balloon
await page.evaluate(() => window.__zef.goto(0, 0));
await page.waitForTimeout(2500);
const bal = await page.evaluate(() => window.__zef.localScreen(0, -4.4, 2.6, 2.6));
await page.mouse.click(bal.x, bal.y);
await page.waitForTimeout(4000);
await page.screenshot({ path: 'scripts/out/extra-03-balloon-flight.png', timeout: 120000 });
console.log('balloon', JSON.stringify(await page.evaluate(() => ({ cut: window.__zef.game().cutscene, scene: window.__zef.game().scene }))));
await page.waitForTimeout(9000);
console.log('after flight', JSON.stringify(await page.evaluate(() => ({ cut: window.__zef.game().cutscene, scene: window.__zef.game().scene }))));
await page.screenshot({ path: 'scripts/out/extra-04-arrived-hall.png', timeout: 120000 });
await page.evaluate(() => window.__zef.castle('garden'));
await page.waitForTimeout(5000);
await page.screenshot({ path: 'scripts/out/extra-05-garden.png', timeout: 120000 });
console.log(logs.slice(0, 20).join('\n'));
await browser.close();
