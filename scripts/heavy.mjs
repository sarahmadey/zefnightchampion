import { chromium } from 'playwright';
const [id = '2', w = '390', h = '844'] = process.argv.slice(2);
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: +w, height: +h }, deviceScaleFactor: 1 });
await page.addInitScript(() => localStorage.setItem('zefs-dry-night-quest:welcomed', '1'));
await page.goto(`http://127.0.0.1:5173/?debug&noevents&lit=15&at=${id}&cam=follow`, { waitUntil: 'load' });
await page.waitForTimeout(8000);
const rows = await page.evaluate(() => window.__zef.heavy(30));
console.log(rows.map((r) => `${String(r.tris).padStart(8)} ${r.shadow ? 'S' : ' '} ${r.name}`).join('\n'));
console.log(JSON.stringify(await page.evaluate(() => window.__zef.info())));
await browser.close();
